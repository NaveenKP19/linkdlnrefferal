CREATE TABLE IF NOT EXISTS outreach_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    connection_id BIGINT REFERENCES connections(id) ON DELETE SET NULL,
    contact_name VARCHAR(100) NOT NULL,
    company VARCHAR(150),
    profile_url VARCHAR(500),
    email VARCHAR(200),
    invite_status VARCHAR(50) NOT NULL DEFAULT 'Not Sent',
    invite_note TEXT,
    referral_message TEXT,
    invite_sent_at TIMESTAMP WITHOUT TIME ZONE,
    accepted_at TIMESTAMP WITHOUT TIME ZONE,
    last_contacted_at TIMESTAMP WITHOUT TIME ZONE,
    next_follow_up_at TIMESTAMP WITHOUT TIME ZONE,
    email_subject VARCHAR(200),
    email_body TEXT,
    email_status VARCHAR(50) NOT NULL DEFAULT 'Draft',
    email_sent_at TIMESTAMP WITHOUT TIME ZONE,
    notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_outreach_messages_user_id ON outreach_messages(user_id);
CREATE INDEX IF NOT EXISTS idx_outreach_messages_invite_status ON outreach_messages(invite_status);
