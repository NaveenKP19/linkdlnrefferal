CREATE TABLE IF NOT EXISTS linkedin_oauth_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_hash VARCHAR(64) NOT NULL,
    nonce VARCHAR(200) NOT NULL,
    user_id BIGINT REFERENCES user_accounts(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_linkedin_oauth_state_hash UNIQUE (state_hash)
);

CREATE INDEX IF NOT EXISTS idx_linkedin_oauth_state_expires_at ON linkedin_oauth_states(expires_at);

CREATE TABLE IF NOT EXISTS linkedin_auth_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash VARCHAR(64) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    user_id BIGINT REFERENCES user_accounts(id) ON DELETE CASCADE,
    pending_subject VARCHAR(200),
    pending_profile TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_linkedin_auth_code_hash UNIQUE (code_hash)
);

CREATE INDEX IF NOT EXISTS idx_linkedin_auth_code_expires_at ON linkedin_auth_codes(expires_at);
CREATE INDEX IF NOT EXISTS idx_linkedin_auth_code_kind ON linkedin_auth_codes(kind);

CREATE TABLE IF NOT EXISTS linkedin_account_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    subject VARCHAR(200) NOT NULL,
    email VARCHAR(200),
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    picture_url VARCHAR(1000),
    connected_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_linkedin_connection_subject UNIQUE (subject),
    CONSTRAINT uk_linkedin_connection_user UNIQUE (user_id)
);

CREATE INDEX IF NOT EXISTS idx_linkedin_connection_user_id ON linkedin_account_connections(user_id);
